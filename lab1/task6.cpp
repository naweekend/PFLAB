#include <iostream>
using namespace std;

int main() {
    // FULL PYRAMID
    cout << "     *\n";
    cout << "    * *\n";
    cout << "   * * *\n";
    cout << "  * * * *\n";
    cout << " * * * * *\n";
    cout << "* * * * * *\n";

    cout << "\n";

    // INVERTED FULL PYRAMID
    cout << "* * * * * *\n";
    cout << " * * * * *\n";
    cout << "  * * * *\n";
    cout << "   * * *\n";
    cout << "    * *\n";
    cout << "     *\n";

    cout << "\n";

    // HOLLOW FULL PYRAMID
    cout << "     *\n";
    cout << "    * *\n";
    cout << "   *   *\n";
    cout << "  *     *\n";
    cout << " *       *\n";
    cout << "* * * * * *\n";

    return 0;
}